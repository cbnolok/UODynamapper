#!/usr/bin/env python3
"""
generate_season_profiles.py — Write the season profiles of Dynamapper's bundled
route file (dynamapper/assets/runtime_specs/land/LandRoutes.kdl) from the
Classic client's season tables.

The tables are read from ClassicUO's SeasonManager.cs as it was at commit
5889a2d6fb35ba5e7f06b7b1d6d70ad1ded30b01 (src/Game/Managers/SeasonManager.cs),
when it still held the tables in code. They match the Classic client 7.0.103.0
entry for entry (README.md: where they are in the client and how they were
compared). Later ClassicUO versions read a seasons.txt instead.

    curl -sL -o SeasonManager.cs https://raw.githubusercontent.com/ClassicUO/ClassicUO/5889a2d6fb35ba5e7f06b7b1d6d70ad1ded30b01/src/Game/Managers/SeasonManager.cs
    python3 -I -B scripts/dev-helpers/seasons/generate_season_profiles.py SeasonManager.cs \\
        dynamapper/assets/runtime_specs/land/LandRoutes.kdl

The profiles replace the lines between the BEGIN and END markers of the route
file; the rest of the file is kept as written. `--check` reports whether the
file is current without writing it.
"""

import argparse
import re
import sys
import textwrap

SOURCE_COMMIT = "5889a2d6fb35ba5e7f06b7b1d6d70ad1ded30b01"
SOURCE_PATH = "src/Game/Managers/SeasonManager.cs"
BEGIN_MARKER = "// BEGIN season profiles generated by scripts/dev-helpers/seasons/generate_season_profiles.py"
END_MARKER = "// END season profiles"

# The client's season numbers, in its order (the 0xBC packet's season byte).
SEASONS = ("spring", "summer", "fall", "winter", "desolation")
# The functions of SeasonManager.cs that switch static graphics, by season. Summer and winter change no static.
STATIC_FUNCTIONS = {"spring": "GetSpringGraphic", "fall": "GetFallGraphic", "desolation": "GetDesolationGraphic"}
# The array of the winter land graphics. No other season changes land.
WINTER_LAND_ARRAY = "_winterGraphic"
# Where a season applies, as the areas of its profile. The Classic client switches the desolation statics only while
# the player's x is below 0x1800, on every map (FUN_0045c5a0 in the Classic client 7.0.103.0); the profile applies to
# the statics west of that line. y2 0xFFFF reaches past the last row of every map.
AREAS = {"desolation": ["apply-in x1=0 y1=0 x2=0x17FF y2=0xFFFF"]}
AREA_NOTE = ("The Classic client switches these statics while the player stands west of x 0x1800, on every map; "
             "Dynamapper switches the statics that lie west of it (y2 0xFFFF reaches past the last row of every "
             "map). A custom map can change this area, add `apply-in` or `skip-in` areas, for every map or with "
             "map=<n> for one, or remove them to apply the profile everywhere.")
INDENT = "    "
# The width the comments of the route file wrap at.
COMMENT_WIDTH = 118

NOTES = {
    "spring": "Spring: the client changes these statics; land is unchanged.",
    "summer": "Summer: the client draws everything as it is.",
    "fall": "Fall: the client changes these statics; land is unchanged.",
    "winter": "Winter: the client draws snow on these land ids; statics are unchanged.",
    "desolation": "Desolation: the client changes these statics only while the player stands west of x 0x1800, on "
                  "every map (only Felucca and Trammel reach past it). Land is unchanged.",
}


def number(text):
    return int(text, 0)


def winter_land(source):
    """The winter land table: {land id: drawn land id}."""
    pattern = re.compile(re.escape(WINTER_LAND_ARRAY) + r"\[(\d+)\]\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*;")
    table = {number(index): number(value) for index, value in pattern.findall(source)}
    if not table:
        sys.exit(f"no {WINTER_LAND_ARRAY} entries found")
    return table


def function_body(source, name):
    start = re.search(r"\b" + re.escape(name) + r"\s*\(\s*ushort\s+graphic\s*\)\s*\{", source)
    if not start:
        sys.exit(f"function {name} not found")
    depth, index = 1, start.end()
    while depth:
        if index >= len(source):
            sys.exit(f"function {name} is not closed")
        depth += {"{": 1, "}": -1}.get(source[index], 0)
        index += 1
    return source[start.end():index - 1]


def switch_table(body, name):
    """The `case ...: graphic = ...;` groups of a switch: {static id: drawn static id}."""
    table, cases = {}, []
    for token in re.finditer(r"case\s+(0x[0-9A-Fa-f]+|\d+)\s*:|graphic\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*;", body):
        if token.group(1):
            cases.append(number(token.group(1)))
            continue
        if not cases:
            sys.exit(f"{name}: an assignment without a case")
        for case in cases:
            if case in table:
                sys.exit(f"{name}: case {case:#06x} twice")
            table[case] = number(token.group(2))
        cases = []
    if cases:
        sys.exit(f"{name}: cases without an assignment")
    return table


def ranges(table):
    """Runs of consecutive ids with the same target: (first, last, target)."""
    runs = []
    for item_id in sorted(table):
        target = table[item_id]
        if runs and runs[-1][1] + 1 == item_id and runs[-1][2] == target:
            runs[-1][1] = item_id
        else:
            runs.append([item_id, item_id, target])
    return runs


def route_lines(node, table):
    lines = []
    for first, last, target in ranges(table):
        ids = f"0x{first:04X}" if first == last else f"0x{first:04X} 0x{last:04X}"
        lines.append(f"{INDENT}{node} {ids} id=0x{target:04X}")
    return lines


def comment(text, indent=""):
    prefix = indent + "// "
    return textwrap.wrap(text, COMMENT_WIDTH, initial_indent=prefix, subsequent_indent=prefix)


def area_lines(season):
    """The areas of a season the client limits, with their note."""
    if season not in AREAS:
        return []
    return [*comment(AREA_NOTE, INDENT), *(f"{INDENT}{area}" for area in AREAS[season])]


def profiles(source):
    land = {"winter": winter_land(source)}
    statics = {season: switch_table(function_body(source, function), function)
               for season, function in STATIC_FUNCTIONS.items()}
    out = [BEGIN_MARKER, *comment(
        f"From ClassicUO {SOURCE_PATH} at commit {SOURCE_COMMIT}, whose tables match the Classic client 7.0.103.0 "
        "entry for entry. Do not edit by hand: run the script again.")]
    for season in SEASONS:
        out += comment(NOTES[season])
        body = (area_lines(season) + route_lines("land", land.get(season, {}))
                + route_lines("item", statics.get(season, {})))
        if body:
            out += [f'profile "{season}" {{', *body, "}"]
        else:
            out.append(f'profile "{season}" {{}}')
    out.append(END_MARKER)
    return out, {season: (len(land.get(season, {})), len(statics.get(season, {}))) for season in SEASONS}


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("season_manager", help=f"SeasonManager.cs at ClassicUO {SOURCE_COMMIT}")
    parser.add_argument("route_file", help="the LandRoutes.kdl to update")
    parser.add_argument("--check", action="store_true", help="only report whether the file is current")
    args = parser.parse_args()

    with open(args.season_manager, encoding="utf-8-sig") as file:
        generated, counts = profiles(file.read())
    with open(args.route_file, encoding="utf-8") as file:
        lines = file.read().split("\n")
    try:
        begin, end = lines.index(BEGIN_MARKER), lines.index(END_MARKER)
    except ValueError:
        sys.exit(f"{args.route_file}: the BEGIN and END markers are missing")
    updated = lines[:begin] + generated + lines[end + 1:]
    for season, (land, items) in counts.items():
        print(f"{season}: {land} land id(s), {items} static id(s)")
    if updated == lines:
        print(f"{args.route_file} is current")
        return
    if args.check:
        sys.exit(f"{args.route_file} is out of date")
    with open(args.route_file, "w", encoding="utf-8") as file:
        file.write("\n".join(updated))
    print(f"wrote {args.route_file}")


if __name__ == "__main__":
    main()
