/// Compute the 2-subset partition bitmask for a given partition ID.
/// Bit i is set if pixel i belongs to subset 1.
#[inline]
pub fn part2_bitmask(part_id: usize) -> u16 {
    let base = part_id * 16;
    let mut mask = 0u16;
    for x in 0..16 {
        mask |= (BC7_PARTITION2[base + x] as u16) << x;
    }
    mask
}

// RGB endpoints for the solid Mode 5 path, whose shared selector is 1.
// BC7 expands 7-bit endpoints by bit replication, then interpolates with
// weights 43/64 and 21/64 (including the specified integer rounding).
// https://learn.microsoft.com/en-us/windows/win32/direct3d11/bc7-format
pub const BC7_MODE5_OPTIMAL_ENDPOINTS: [(u8,u8);256] = mode5_solid_endpoints();

const fn mode5_solid_endpoints() -> [(u8,u8);256] {
    let mut result = [(0, 0); 256];
    let mut color = 0u32;
    while color < 256 {
        let mut low = 0u32;
        'search: while low < 128 {
            let mut high = low;
            while high < 128 {
                let lo = (low << 1) | (low >> 6);
                let hi = (high << 1) | (high >> 6);
                if (lo * 43 + hi * 21 + 32) >> 6 == color {
                    result[color as usize] = (low as u8, high as u8);
                    break 'search;
                }
                high += 1;
            }
            low += 1;
        }
        assert!(low < 128);
        color += 1;
    }
    result
}
