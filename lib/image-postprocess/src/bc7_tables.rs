/// Compute the 2-subset partition bitmask for a given partition ID.
/// Bit i is set if pixel i belongs to subset 1.
#[inline]
pub fn part2_bitmask(part_id: usize) -> u16 {
    let base = part_id * 16;
    let mut mask = 0u16;
    for x in 0..16 {
        mask |= (BC7_PARTITION2[base + x] as u16) << x;
    }
    mask
}

