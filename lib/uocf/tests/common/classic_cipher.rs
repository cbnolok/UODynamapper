fn put16(bytes: &mut [u8], at: usize, value: u16) { bytes[at..at + 2].copy_from_slice(&value.to_le_bytes()); }
fn put32(bytes: &mut [u8], at: usize, value: u32) { bytes[at..at + 4].copy_from_slice(&value.to_le_bytes()); }
fn code_va(at: usize) -> u32 { IMAGE_BASE + TEXT_RVA + at as u32 }
fn relative(bytes: &mut [u8], at: usize, target: usize) {
    put32(bytes, TEXT_RAW + at + 1, code_va(target).wrapping_sub(code_va(at) + 5));
}

pub fn image_with(layout: Layout, removed: bool, code_offset: usize) -> Vec<u8> {
    let mut bytes = vec![0; DATA_RAW + DATA_SIZE];
    bytes[..2].copy_from_slice(b"MZ"); put32(&mut bytes, 0x3c, 0x80);
    bytes[0x80..0x84].copy_from_slice(b"PE\0\0"); put16(&mut bytes, 0x84, 0x14c);
    put16(&mut bytes, 0x86, 2); put16(&mut bytes, 0x94, 0xe0); put16(&mut bytes, OPTIONAL_OFFSET, 0x10b);
    put32(&mut bytes, OPTIONAL_OFFSET + 28, IMAGE_BASE); put32(&mut bytes, OPTIONAL_OFFSET + 32, 0x1000);
    put32(&mut bytes, OPTIONAL_OFFSET + 36, 0x200); put32(&mut bytes, OPTIONAL_OFFSET + 56, 0x5000);
    put32(&mut bytes, OPTIONAL_OFFSET + 60, TEXT_RAW as u32); put32(&mut bytes, OPTIONAL_OFFSET + 92, 16);
    for (index, (name, rva, raw, size, flags)) in [
        (&b".text"[..], TEXT_RVA, TEXT_RAW, TEXT_SIZE, CODE_CHARACTERISTICS),
        (&b".data"[..], DATA_RVA, DATA_RAW, DATA_SIZE, WRITABLE_DATA),
    ].into_iter().enumerate() {
        let at = SECTION_HEADERS + index * SECTION_HEADER_SIZE;
        bytes[at..at + name.len()].copy_from_slice(name); put32(&mut bytes, at + 8, size as u32);
        put32(&mut bytes, at + 12, rva); put32(&mut bytes, at + 16, size as u32);
        put32(&mut bytes, at + 20, raw as u32); put32(&mut bytes, at + 36, flags);
    }
    bytes[TEXT_RAW..DATA_RAW].fill(0xcc);
    let (code, patch, keys, seed, globals, writer, call) = match layout {
        Layout::Optimized => (OPTIMIZED, 0x44, [0x7d, 0x90], SEED_OPTIMIZED, &[(40usize)][..],
            &b"\x57\x56\x8b\xcb\xe8\0\0\0\0\x5f\x5e\x5b\x5d\xc2\x04\0"[..], 4),
        Layout::Unoptimized => (UNOPTIMIZED, 0x58, [0xb4, 0xd0], SEED_UNOPTIMIZED, &[1usize, 12, 68][..],
            &b"\x8b\x55\xfc\x52\x8b\x45\x08\x50\x8b\x4d\xf0\xe8\0\0\0\0\x8b\xe5\x5d\xc2\x04\0"[..], 11),
        Layout::MultiKey => (MULTIKEY, 0x48, [0x9b, 0xb3], SEED_OPTIMIZED, &[40usize][..],
            &b"\x57\x56\x8b\xcb\xe8\0\0\0\0\x5f\x5e\x5b\x5d\xc2\x04\0"[..], 4),
    };
    bytes[TEXT_RAW + code_offset..][..code.len()].copy_from_slice(code);
    for (at, key) in keys.into_iter().zip([KEY_HI, KEY_LO]) { put32(&mut bytes, TEXT_RAW + code_offset + at, key); }
    if let Layout::MultiKey = layout {
        for (at, key) in [(0xa3, KEY_HI), (0xc2, KEY_LO), (0x6f, GUARD_GLOBAL), (0xe9, GUARD_GLOBAL)] {
            put32(&mut bytes, TEXT_RAW + code_offset + at, key);
        }
        relative(&mut bytes, code_offset + 0x79, FAILURE_OFFSET);
        bytes[TEXT_RAW + FAILURE_OFFSET] = 0xc3;
    }
    if removed { bytes[TEXT_RAW + code_offset + patch..][..2].fill(0x90); }
    bytes[TEXT_RAW + SEED_OFFSET..][..seed.len()].copy_from_slice(seed);
    for &at in globals { put32(&mut bytes, TEXT_RAW + SEED_OFFSET + at, SEED_GLOBAL); }
    bytes[TEXT_RAW + WRITER_OFFSET..][..writer.len()].copy_from_slice(writer);
    relative(&mut bytes, WRITER_OFFSET + call, code_offset);
    bytes
}

pub fn image() -> Vec<u8> { image_with(Layout::Optimized, false, CODE_OFFSET) }

pub fn ambiguous_image() -> Vec<u8> {
    let mut bytes = image();
    let duplicate = bytes[TEXT_RAW + CODE_OFFSET..TEXT_RAW + CODE_OFFSET + OPTIMIZED.len()].to_vec();
    bytes[TEXT_RAW + MOVED_CODE_OFFSET..][..duplicate.len()].copy_from_slice(&duplicate);
    let writer = bytes[TEXT_RAW + WRITER_OFFSET..TEXT_RAW + WRITER_OFFSET + 16].to_vec();
    bytes[TEXT_RAW + SECOND_WRITER_OFFSET..][..writer.len()].copy_from_slice(&writer);
    relative(&mut bytes, SECOND_WRITER_OFFSET + 4, MOVED_CODE_OFFSET);
    bytes
}
