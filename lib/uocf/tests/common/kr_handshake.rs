impl Fixture {
    pub fn offset(&self, va: u32) -> usize { (va - self.image_base) as usize }
}

fn word(bytes: &mut [u8], at: usize, value: u32) {
    bytes[at..at + WORD].copy_from_slice(&value.to_le_bytes());
}

struct Builder {
    text: Vec<u8>, rdata: Vec<u8>, next_text: usize, next_rtti: usize,
    image_base: u32, text_va: u32, rdata_va: u32,
}

impl Builder {
    fn code(&mut self, bytes: &[u8]) -> u32 {
        let at = self.next_text;
        self.next_text = (at + bytes.len()).next_multiple_of(ALIGNMENT);
        self.text[at..at + bytes.len()].copy_from_slice(bytes);
        self.text_va + at as u32
    }
    fn value(&mut self, va: u32, offset: usize, value: u32) {
        word(&mut self.text, (va - self.text_va) as usize + offset, value);
    }
    fn edge(&mut self, va: u32, operand: usize, target: u32) {
        self.value(va, operand, target.wrapping_sub(va + operand as u32 + WORD as u32));
    }
    fn vtable(&mut self, name: &str) -> u32 {
        let at = self.next_rtti; self.next_rtti += RTTI_SIZE;
        let descriptor = at + 0x20; let hierarchy = at + 0xc0;
        let bases = at + 0xd0; let base = at + 0xe0;
        let vtable = at + 0x120; let type_info = at + 0x180;
        word(&mut self.rdata, at + 12, self.rdata_va + descriptor as u32);
        word(&mut self.rdata, at + 16, self.rdata_va + hierarchy as u32);
        word(&mut self.rdata, descriptor, self.rdata_va + type_info as u32);
        self.rdata[descriptor + 8..descriptor + 8 + name.len()].copy_from_slice(name.as_bytes());
        word(&mut self.rdata, hierarchy + 8, 1);
        word(&mut self.rdata, hierarchy + 12, self.rdata_va + bases as u32);
        word(&mut self.rdata, bases, self.rdata_va + base as u32);
        word(&mut self.rdata, base, self.rdata_va + descriptor as u32);
        word(&mut self.rdata, vtable - WORD, self.rdata_va + at as u32);
        word(&mut self.rdata, vtable, self.text_va + STUB as u32);
        word(&mut self.rdata, type_info, self.text_va + STUB as u32);
        self.rdata_va + vtable as u32
    }
    fn shared(&mut self, name: &str, callback: bool, allocator: u32, enter: u32, leave: u32) -> u32 {
        let mut bytes = if callback { CALLBACK_SHARED_FULL.to_vec() } else { SHARED_FULL.to_vec() };
        let vtable = self.vtable(name);
        word(&mut bytes, 1, allocator); word(&mut bytes, 0x29, enter);
        word(&mut bytes, 0x48, leave); word(&mut bytes, 0x5d, vtable);
        let va = self.code(&bytes); self.edge(va, 0x37, self.text_va + ENGINE as u32); va
    }
    fn imports(&mut self) -> (u32, u32, u32) {
        let rva = |offset: usize| self.rdata_va - self.image_base + offset as u32;
        for (descriptor, int, iat, module) in [
            (IMPORT_DESCRIPTOR, THREAD_INT, THREAD_IAT, THREAD_MODULE),
            (IMPORT_DESCRIPTOR + 20, SOCKET_INT, SOCKET_IAT, SOCKET_MODULE),
        ] {
            word(&mut self.rdata, descriptor, rva(int));
            word(&mut self.rdata, descriptor + 12, rva(module));
            word(&mut self.rdata, descriptor + 16, rva(iat));
        }
        for table in [THREAD_INT, THREAD_IAT] {
            word(&mut self.rdata, table, rva(ENTER_NAME));
            word(&mut self.rdata, table + WORD, rva(LEAVE_NAME));
        }
        for table in [SOCKET_INT, SOCKET_IAT] { word(&mut self.rdata, table, ORDINAL_HTONL); }
        for (offset, value) in [(ENTER_NAME + 2, "EnterCriticalSection"), (LEAVE_NAME + 2, "LeaveCriticalSection"),
            (THREAD_MODULE, "KERNEL32.dll"), (SOCKET_MODULE, "WS2_32.dll")] {
            self.rdata[offset..offset + value.len()].copy_from_slice(value.as_bytes());
        }
        (self.rdata_va + THREAD_IAT as u32, self.rdata_va + THREAD_IAT as u32 + WORD as u32, self.rdata_va + SOCKET_IAT as u32)
    }
}

pub fn modern(connect_offset: usize) -> Fixture {
    modern_layout(connect_offset, HELPER_START, IMAGE_BASE, RDATA_RVA, DATA_RVA)
}

/// Addresses are intentionally unrelated to any shipped KR profile. Reserved text 0x200..0x600 is left clear.
pub fn modern_layout(connect_offset: usize, helper_start: usize, image_base: u32, rdata_rva: u32, data_rva: u32) -> Fixture {
    assert!(connect_offset + STOCK_CODE.len() < helper_start && helper_start >= HELPER_START);
    assert!(rdata_rva >= TEXT_RVA + TEXT_SIZE as u32 && data_rva >= rdata_rva + RDATA_SIZE as u32);
    let text_va = image_base + TEXT_RVA; let rdata_va = image_base + rdata_rva; let data_va = image_base + data_rva;
    let mut b = Builder { text: vec![0xcc; TEXT_SIZE], rdata: vec![0; RDATA_SIZE], next_text: helper_start,
        next_rtti: RTTI_START, image_base, text_va, rdata_va };
    for offset in [STUB, ENGINE, STRING_COPY, VECTOR_PUSH, REGISTER] { b.text[offset] = 0xc3; }
    let (enter, leave, htonl) = b.imports();
    let allocator = data_va; let game = data_va + 0x10; let control = game + WORD as u32;
    let heap = b.code(&HEAP_ALLOCATOR);
    for (operand, value) in [(1, allocator), (0x16, enter), (0x38, leave)] { b.value(heap, operand, value); }
    b.edge(heap, 0x27, text_va + ENGINE as u32);
    let seed = b.code(&SEED_CONSTRUCTOR);
    let seed_vtable = b.vtable(SEED_TYPE);
    for (operand, value) in [(1, allocator), (0x1c, seed_vtable), (0x30, enter), (0x4e, leave)] { b.value(seed, operand, value); }
    b.edge(seed, 0x3d, text_va + ENGINE as u32);
    let seed_shared = b.shared(SEED_SHARED_TYPE, false, allocator, enter, leave);
    let callback_shared = b.shared(CALLBACK_SHARED_TYPE, true, allocator, enter, leave);
    let huffman_shared = b.shared(HUFFMAN_SHARED_TYPE, false, allocator, enter, leave);
    let huffman_constructor = b.code(&HUFFMAN_CONSTRUCTOR);
    let huffman_vtable = b.vtable(HUFFMAN_TYPE);
    for (operand, value) in [(1, allocator), (0xe, huffman_vtable), (0x34, enter), (0x52, leave)] { b.value(huffman_constructor, operand, value); }
    b.edge(huffman_constructor, 0x41, text_va + ENGINE as u32);
    let receive = b.code(&RECEIVE_TRANSFORM); b.edge(receive, 0x2b, text_va + VECTOR_PUSH as u32);
    let send = b.code(&SEND91_PREFIX);
    b.edge(send, 0x2f, text_va + STRING_COPY as u32); b.edge(send, 0x48, text_va + STRING_COPY as u32);
    b.value(send, 0x4e, control); b.value(send, 0x56, game);
    let disconnect = b.code(&DISCONNECT_FULL);
    for (operand, value) in [(7, data_va + 0x20), (0x15, data_va + 0x24), (0x62, game), (0x6c, control)] { b.value(disconnect, operand, value); }
    let append = b.code(&APPEND_PREFIX);
    let handler = b.code(&vec![0xcc; E3_SIZE]);
    let handler_offset = (handler - text_va) as usize;
    b.text[handler_offset..handler_offset + E3_PROLOGUE.len()].copy_from_slice(&E3_PROLOGUE);
    b.text[handler_offset + E3_FAILURE..handler_offset + E3_FAILURE + 13].copy_from_slice(&[0x8b, 0x3d, 0, 0, 0, 0, 0x6a, 0x01, 0xe8, 0, 0, 0, 0]);
    b.value(handler, E3_FAILURE + 2, data_va + 0x30); b.edge(handler, E3_FAILURE + 9, disconnect);
    let tail = handler + E3_TAIL as u32;
    b.text[handler_offset + E3_TAIL..handler_offset + E3_TAIL + E3_HUFFMAN_TAIL.len()].copy_from_slice(&E3_HUFFMAN_TAIL);
    for (operand, target) in [(3, heap), (17, huffman_constructor), (38, huffman_shared), (45, text_va + STUB as u32), (109, receive), (164, send)] { b.edge(tail, operand, target); }
    b.value(tail, 0x52, control); b.value(tail, 0x59, game);
    b.text[handler_offset + E3_RETURN..handler_offset + E3_RETURN + 9].copy_from_slice(&[0x5f, 0x5e, 0x5b, 0x8b, 0xe5, 0x5d, 0xc2, 0x08, 0x00]);
    let connect = text_va + connect_offset as u32;
    b.text[connect_offset..connect_offset + STOCK_CODE.len()].copy_from_slice(&STOCK_CODE);
    let callback_vtable = b.vtable(CALLBACK_TYPE);
    for (operand, value) in [(1, allocator), (0x1b, enter), (0x31, leave), (0x6d, htonl), (0x8b, control),
        (0x93, game), (0xfc, control), (0x103, game), (0x14e, allocator), (0x161, enter), (0x18a, callback_vtable),
        (0x194, handler), (0x1d5, control), (0x1dc, game)] { b.value(connect, operand, value); }
    for (operand, target) in [(0x29, text_va + ENGINE as u32), (0x46, seed), (0x5b, seed_shared),
        (0x62, text_va + STUB as u32), (0x86, append), (0x16f, text_va + ENGINE as u32),
        (0x1a9, callback_shared), (0x1b0, text_va + STUB as u32), (0x1f7, text_va + REGISTER as u32)] { b.edge(connect, operand, target); }
    let mut bytes = vec![0; TEXT_RVA as usize];
    bytes[..2].copy_from_slice(b"MZ"); word(&mut bytes, 0x3c, PE_OFFSET as u32);
    bytes[PE_OFFSET..PE_OFFSET + 4].copy_from_slice(b"PE\0\0");
    bytes[PE_OFFSET + 4..PE_OFFSET + 6].copy_from_slice(&0x14cu16.to_le_bytes());
    bytes[PE_OFFSET + 6..PE_OFFSET + 8].copy_from_slice(&3u16.to_le_bytes());
    bytes[PE_OFFSET + 20..PE_OFFSET + 22].copy_from_slice(&(OPTIONAL_SIZE as u16).to_le_bytes());
    bytes[OPTIONAL..OPTIONAL + 2].copy_from_slice(&0x10bu16.to_le_bytes());
    word(&mut bytes, OPTIONAL + 28, image_base); word(&mut bytes, OPTIONAL + 32, TEXT_RVA);
    word(&mut bytes, OPTIONAL + 36, TEXT_RVA); word(&mut bytes, OPTIONAL + 56, data_rva + DATA_SIZE as u32);
    word(&mut bytes, OPTIONAL + 60, TEXT_RVA); word(&mut bytes, OPTIONAL + 92, 16);
    word(&mut bytes, OPTIONAL + 96 + 8, rdata_rva + IMPORT_DESCRIPTOR as u32);
    word(&mut bytes, OPTIONAL + 96 + 12, 60);
    for (index, (name, rva, data, flags)) in [
        (".text", TEXT_RVA, b.text, 0x6000_0020u32), (".rdata", rdata_rva, b.rdata, 0x4000_0040),
        (".data", data_rva, vec![0; DATA_SIZE], 0xc000_0040),
    ].into_iter().enumerate() {
        let header = SECTION_HEADERS + index * 40;
        bytes[header..header + name.len()].copy_from_slice(name.as_bytes());
        for (offset, value) in [(8, data.len() as u32), (12, rva), (16, data.len() as u32), (20, rva), (36, flags)] { word(&mut bytes, header + offset, value); }
        bytes.resize(rva as usize, 0); bytes.extend(data);
    }
    Fixture { bytes, connect, handler, tail, huffman_constructor, huffman_shared, heap, receive, send, disconnect,
        allocator, game, control, htonl, image_base, text_va, rdata_va, data_va }
}

pub fn current_patch(fixture: &mut Fixture) { replace(fixture, false); }
pub fn previous_patch(fixture: &mut Fixture) { replace(fixture, true); }

fn replace(fixture: &mut Fixture, previous: bool) {
    let base = fixture.offset(fixture.connect);
    let bytes = &mut fixture.bytes;
    bytes[base + PATCH_START..base + PATCH_START + AUTH_SEED.len()].copy_from_slice(&AUTH_SEED);
    word(bytes, base + PATCH_START + 9, fixture.htonl); bytes[base + STATE] = 2;
    bytes[base + CALLBACK_START..base + PATCH_END].fill(0x90);
    let mut callback = HUFFMAN_AND_LOGIN.to_vec();
    if previous { callback.drain(OLD_FAILURE_LOAD); }
    word(&mut callback, 46, fixture.game);
    let mut calls = vec![(3, fixture.heap), (17, fixture.huffman_constructor), (30, fixture.huffman_shared),
        (51, fixture.receive), (60, fixture.send), (65, fixture.connect + PATCH_END as u32)];
    calls.extend(if previous { [(72, fixture.disconnect), (77, fixture.connect + SEED_CLEANUP as u32)] }
        else { [(76, fixture.disconnect), (81, fixture.connect + SEED_CLEANUP as u32)] });
    for (operand, target) in calls {
        word(&mut callback, operand, target.wrapping_sub(fixture.connect + CALLBACK_START as u32 + operand as u32 + WORD as u32));
    }
    bytes[base + CALLBACK_START..base + CALLBACK_START + callback.len()].copy_from_slice(&callback);
}
