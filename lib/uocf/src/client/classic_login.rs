/// Canonical optimized fixture. Runtime detection validates the complete graph below.
pub(super) const PATTERN: CipherPattern = CipherPattern {
    bytes: OPTIMIZED, patch_at: OPTIMIZED_PATCH, stock: &[0x32, 0xd1], patched: &NOPS,
    required_va: None, previous: None,
};

pub(super) struct ResolvedClassicCipher {
    pub offset: usize,
    pub stock: [u8; 2],
    pub removed: bool,
    pub keys: LoginMasterKeys,
    pub algorithm: LoginCipherAlgorithm,
}

fn matches(bytes: &[u8], template: &[u16], patch: Option<usize>) -> bool {
    bytes.len() == template.len() && bytes.iter().zip(template).enumerate().all(|(at, (byte, expected))| {
        patch.is_some_and(|start| (start..start + NOPS.len()).contains(&at))
            || *expected == ANY || u16::from(*byte) == *expected
    })
}

fn word(bytes: &[u8], at: usize) -> Option<u32> {
    Some(u32::from_le_bytes(bytes.get(at..at.checked_add(DWORD_SIZE)?)?.try_into().ok()?))
}

fn seed_initialization(image: &Image<'_>, code: &[u8], unoptimized: bool) -> bool {
    let (template, globals): (&[u16], &[usize]) = if unoptimized {
        (SEED_UNOPTIMIZED, &UNOPTIMIZED_SEED_GLOBALS)
    } else {
        (SEED_OPTIMIZED, &[OPTIMIZED_SEED_GLOBAL])
    };
    if code.len() < template.len() { return false; }
    code.windows(template.len()).filter(|window| matches(window, template, None)).filter(|window| {
        let Some(global) = word(window, globals[0]) else { return false };
        image.is_writable_data(global, DWORD_SIZE) && globals.iter().all(|&at| word(window, at) == Some(global))
    }).count() == 1
}

fn writer_calls(image: &Image<'_>, code: &[u8], code_va: u32, target: u32, unoptimized: bool) -> bool {
    let (template, call) = if unoptimized {
        (PACKET_WRITER_UNOPTIMIZED, UNOPTIMIZED_WRITER_CALL)
    } else {
        (PACKET_WRITER_OPTIMIZED, OPTIMIZED_WRITER_CALL)
    };
    if code.len() < template.len() { return false; }
    code.windows(template.len()).enumerate().filter(|(_, window)| matches(window, template, None)).any(|(at, _)| {
        u32::try_from(at + call).ok().and_then(|delta| code_va.checked_add(delta))
            .and_then(|va| image.call_target(va)) == Some(target)
    })
}

/// Locate supported early Classic loops in either XOR or NOP form. Ambiguity remains visible to the caller.
pub(super) fn locate(bytes: &[u8], pe: &PeImage) -> Vec<ResolvedClassicCipher> {
    let Ok((code, base)) = code_section(bytes, pe) else { return Vec::new() };
    let Some(section) = pe.section(".text") else { return Vec::new() };
    let image = Image::new(bytes, pe);
    let mut resolved = Vec::new();
    for (template, patch, keys, algorithm) in [
        (OPTIMIZED, OPTIMIZED_PATCH, OPTIMIZED_KEYS, LoginCipherAlgorithm::ClassicRotation),
        (UNOPTIMIZED, UNOPTIMIZED_PATCH, UNOPTIMIZED_KEYS, LoginCipherAlgorithm::ClassicRotation),
        (MULTIKEY, MULTIKEY_PATCH, MULTIKEY_KEYS, LoginCipherAlgorithm::ClassicMultiKey12536),
    ] {
        let unoptimized = template == UNOPTIMIZED;
        if code.len() < template.len() || !seed_initialization(&image, code, unoptimized) { continue; }
        for (at, window) in code.windows(template.len()).enumerate() {
            if !matches(window, template, Some(patch)) { continue; }
            let stock = [template[patch] as u8, template[patch + 1] as u8];
            let written = &window[patch..patch + stock.len()];
            if written != stock && written != NOPS { continue; }
            let Some(function) = u32::try_from(at).ok().and_then(|delta| section.virtual_address.checked_add(delta)) else { continue };
            if !writer_calls(&image, code, section.virtual_address, function, unoptimized) { continue; }
            let Some(key_1) = word(window, keys[0]) else { continue };
            let Some(key_2) = word(window, keys[1]) else { continue };
            if algorithm == LoginCipherAlgorithm::ClassicMultiKey12536 {
                let Some(guard) = word(window, MULTIKEY_GUARD_READ) else { continue };
                if word(window, MULTIKEY_GUARD_WRITE) != Some(guard) || !image.is_writable_data(guard, DWORD_SIZE)
                    || word(window, MULTIKEY_REPEATED_KEYS[0]) != Some(key_1)
                    || word(window, MULTIKEY_REPEATED_KEYS[1]) != Some(key_2)
                    || function.checked_add(MULTIKEY_FAILURE_CALL as u32).and_then(|va| image.rel_target(va, CALL_REL32)).is_none()
                { continue; }
            }
            resolved.push(ResolvedClassicCipher {
                offset: base + at + patch, stock, removed: written == NOPS,
                keys: LoginMasterKeys { key_1, key_2, first_round: key_1 }, algorithm,
            });
        }
    }
    resolved
}

#[cfg(test)]
#[path = "../../tests/common/classic_cipher.rs"]
pub(crate) mod fixture;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn relocated_loops_with_changed_keys_are_located_in_either_form() {
        for layout in [fixture::Layout::Optimized, fixture::Layout::Unoptimized, fixture::Layout::MultiKey] {
            for removed in [false, true] {
                let bytes = fixture::image_with(layout, removed, fixture::MOVED_CODE_OFFSET);
                let sites = locate(&bytes, &PeImage::parse(&bytes).unwrap());
                assert_eq!(sites.len(), 1);
                assert_eq!(sites[0].removed, removed);
                assert_eq!(sites[0].keys.key_1, fixture::KEY_HI);
                assert_eq!(sites[0].keys.key_2, fixture::KEY_LO);
            }
        }
    }

    #[test]
    fn missing_seed_writer_edge_unknown_instructions_and_ambiguity_are_refused() {
        for at in [fixture::SEED_OFFSET, fixture::WRITER_OFFSET, fixture::CODE_OFFSET + fixture::CORRUPT_OFFSET] {
            let mut bytes = fixture::image();
            bytes[fixture::TEXT_RAW + at] ^= 1;
            assert!(locate(&bytes, &PeImage::parse(&bytes).unwrap()).is_empty());
        }
        let bytes = fixture::ambiguous_image();
        assert_eq!(locate(&bytes, &PeImage::parse(&bytes).unwrap()).len(), 2);
    }

    #[test]
    fn truncated_images_and_unwritable_seed_globals_are_refused() {
        let mut bytes = fixture::image();
        bytes[fixture::DATA_CHARACTERISTICS_OFFSET..][..DWORD_SIZE].copy_from_slice(&fixture::READONLY_DATA.to_le_bytes());
        assert!(locate(&bytes, &PeImage::parse(&bytes).unwrap()).is_empty());
        let bytes = fixture::image();
        for length in [0, fixture::TEXT_RAW, bytes.len() / 2] {
            assert!(locate(&bytes[..length], &PeImage::parse(&bytes).unwrap()).is_empty());
        }
    }

    #[test]
    fn multikey_guard_key_copies_and_patch_instruction_must_agree() {
        const CORRUPT_FIELDS: [usize; 4] = [
            MULTIKEY_PATCH, MULTIKEY_REPEATED_KEYS[0], MULTIKEY_GUARD_WRITE, MULTIKEY_FAILURE_CALL,
        ];
        for at in CORRUPT_FIELDS {
            let mut bytes = fixture::image_with(fixture::Layout::MultiKey, false, fixture::CODE_OFFSET);
            bytes[fixture::TEXT_RAW + fixture::CODE_OFFSET + at] ^= 1;
            assert!(locate(&bytes, &PeImage::parse(&bytes).unwrap()).is_empty());
        }
    }
}
