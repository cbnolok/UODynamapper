struct Shape {
    bytes: &'static [u8],
    operands: &'static [usize],
}

impl Shape {
    fn pattern(&self) -> Vec<u16> {
        let mut result: Vec<_> = self.bytes.iter().map(|byte| u16::from(*byte)).collect();
        for &at in self.operands {
            result[at..at + WORD_SIZE].fill(PATTERN_WILDCARD);
        }
        result
    }

    fn matches(&self, image: &Image<'_>, va: u32) -> bool {
        image.is_code(va) && image.read(va, self.bytes.len()).is_some_and(|bytes| {
            bytes.iter().zip(self.bytes).enumerate().all(|(at, (actual, expected))| {
                actual == expected || self.operands.iter().any(|operand| (*operand..*operand + WORD_SIZE).contains(&at))
            })
        })
    }
}

