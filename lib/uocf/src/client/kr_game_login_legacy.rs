#[derive(Debug, Clone, PartialEq, Eq)]
struct Helpers {
    heap_new: u32,
    huffman_constructor: u32,
    huffman_shared: u32,
    huffman_copy: u32,
    add_receive_transform: u32,
    send91: u32,
    huffman_release: u32,
    disconnect: u32,
    game_global: u32,
}

fn word(image: &Image<'_>, base: u32, offset: usize) -> Option<u32> {
    image.u32(base.checked_add(u32::try_from(offset).ok()?)?)
}

fn call(image: &Image<'_>, base: u32, offset: usize) -> Option<u32> {
    image.call_target(base.checked_add(u32::try_from(offset).ok()?)?)
}

fn require(condition: bool) -> Option<()> {
    condition.then_some(())
}

/// These old functions use the original MSVC EH prolog and a FuncInfo handler thunk.
fn func_info(image: &Image<'_>, handler: u32) -> Option<u32> {
    let thunk = image.read(handler, 10)?;
    require(image.is_code(handler) && thunk[0] == 0xb8 && thunk[5] == 0xe9)?;
    let runtime = image.jump_target(handler.checked_add(5)?)?;
    require(image.read(runtime, 10)? == [0x55, 0x8b, 0xec, 0x83, 0xec, 0x08, 0x53, 0x56, 0x57, 0xfc])?;
    let info = word(image, handler, 1)?;
    require(image.is_data(info, FUNC_INFO_SIZE) && image.u32(info)? == EH_MAGIC)?;
    let states = word(image, info, 4)?;
    require(states <= MAX_EH_STATES)?;
    let unwind = word(image, info, 8)?;
    require(states == 0 || image.is_data(unwind, states as usize * UNWIND_ENTRY_SIZE))?;
    Some(info)
}

fn helper(image: &Image<'_>, shape: &Shape, va: u32, eh_prolog: u32) -> Option<()> {
    require(shape.matches(image, va))?;
    require(call(image, va, 5)? == eh_prolog)?;
    func_info(image, word(image, va, 1)?)?;
    // Every remaining direct edge must remain executable; absolute operands are checked by its caller.
    for &operand in shape.operands.iter().skip(2) {
        if image.read(va.checked_add(operand as u32)?.checked_sub(1)?, 1)? == [0xe8] {
            call(image, va, operand - 1)?;
        }
    }
    Some(())
}

fn release(image: &Image<'_>, va: u32, eh_prolog: u32) -> Option<u32> {
    helper(image, &GAME_RELEASE, va, eh_prolog)?;
    let inner = call(image, va, 25)?;
    require(RELEASE_INNER.matches(image, inner))?;
    Some(inner)
}

fn action(image: &Image<'_>, unwind: u32, state: usize, prefix: &[u8], suffix: &[u8]) -> Option<u32> {
    let va = word(image, unwind, state * UNWIND_ENTRY_SIZE + WORD_SIZE)?;
    let code = image.read(va, prefix.len() + 5 + suffix.len())?;
    require(code.starts_with(prefix) && code.ends_with(suffix))?;
    call(image, va, prefix.len())
}

fn unwind_graph(image: &Image<'_>, connect: u32, eh_prolog: u32, seed_release: u32, game_release: u32) -> Option<u32> {
    let info = func_info(image, word(image, connect, 9)?)?;
    require(word(image, info, 4)? == EH_STATES as u32)?;
    require(image.read(info.checked_add(12)?, FUNC_INFO_SIZE - 12)?.iter().all(|byte| *byte == 0))?;
    let unwind = word(image, info, 8)?;
    let parents = [u32::MAX, u32::MAX, 1, 2, 1, 1, 1, 6, 7, 6];
    for (state, parent) in parents.into_iter().enumerate() {
        require(word(image, unwind, state * UNWIND_ENTRY_SIZE)? == parent)?;
    }
    let raw_delete = action(image, unwind, 0, &[0xff, 0x75, 0xd4], &[0x59, 0xc3])?;
    require(action(image, unwind, 5, &[0xff, 0x75, 0xd4], &[0x59, 0xc3])? == raw_delete)?;
    require(action(image, unwind, 1, &[0x8d, 0x45, 0xd8, 0x50], &[0xc3])? == seed_release)?;
    for state in [2, 4, 8, 9] {
        require(action(image, unwind, state, &[0x8d, 0x45, 0xe8, 0x50], &[0xc3])? == game_release)?;
    }
    let by_value_release = action(image, unwind, 3, &[0xff, 0x75, 0xd4], &[0xc3])?;
    let huffman_release = action(image, unwind, 6, &[0x8d, 0x45, 0xe0, 0x50], &[0xc3])?;
    require(action(image, unwind, 7, &[0xff, 0x75, 0xd4], &[0xc3])? == huffman_release)?;
    let inner = release(image, seed_release, eh_prolog)?;
    for target in [by_value_release, huffman_release, game_release] {
        require(release(image, target, eh_prolog)? == inner)?;
    }
    // The reused raw-allocation state must call the matching heap's non-null deletion wrapper.
    let code = image.read(raw_delete, 25)?;
    require(code.starts_with(&[0x83, 0x7c, 0x24, 0x04, 0x00, 0x74, 0x11, 0x57, 0xff, 0x74, 0x24, 0x08, 0x8b, 0x3d]))?;
    require(code[18] == 0xe8 && code[23..] == [0x5f, 0xc3])?;
    call(image, raw_delete, 18)?;
    let heap = call(image, connect, 0x23)?;
    require(word(image, raw_delete, 14)? == word(image, heap, 6)?)?;
    Some(huffman_release)
}

fn game_global(image: &Image<'_>, getter: u32, eh_prolog: u32) -> Option<u32> {
    helper(image, &GET_GAME, getter, eh_prolog)?;
    let inner = call(image, getter, 18)?;
    helper(image, &INNER, inner, eh_prolog)?;
    let global = word(image, inner, 12)?;
    require(word(image, inner, 23)? == global.checked_add(WORD_SIZE as u32)?)?;
    require(image.is_writable_data(global, 2 * WORD_SIZE))?;
    Some(global)
}

fn disconnect(image: &Image<'_>, game_global: u32, eh_prolog: u32) -> Option<u32> {
    let mut found = Vec::new();
    for vtable in image.vtables(GAME_TYPE) {
        let filter = word(image, vtable, GAME_FILTER_SLOT as usize)?;
        if !FILTER.matches(image, filter) || call(image, filter, 5) != Some(eh_prolog) {
            continue;
        }
        let target = call(image, filter, 79)?;
        if !(DISCONNECT198.matches(image, target) || DISCONNECT206.matches(image, target)) {
            continue;
        }
        func_info(image, word(image, filter, 1)?)?;
        func_info(image, word(image, target, 15)?)?;
        require(image.is_writable_data(word(image, filter, 74)?, WORD_SIZE))?;
        require(word(image, target, 83)? == game_global)?;
        for operand in [35, 132] {
            require(image.is_writable_data(word(image, target, operand)?, WORD_SIZE))?;
        }
        for operand in [49, 76, 94, 125, 138, 143, 174] {
            call(image, target, operand)?;
        }
        found.push(target);
    }
    found.sort_unstable();
    found.dedup();
    require(found.len() == 1)?;
    found.first().copied()
}

fn validate_helpers(image: &Image<'_>, tail: u32, heap_new: u32, getter: u32, huffman_release: u32, eh_prolog: u32) -> Option<Helpers> {
    require(call(image, tail, 2)? == heap_new && call(image, tail, 78)? == getter)?;
    let huffman_constructor = call(image, tail, 20)?;
    let huffman_shared = call(image, tail, 42)?;
    let huffman_copy = call(image, tail, 65)?;
    let add_receive_transform = call(image, tail, 95)?;
    let send91 = call(image, tail, 119)?;
    let game_release = call(image, tail, 108)?;
    let tail_release = call(image, tail, 135)?;
    helper(image, &HUFFMAN_CONSTRUCTOR, huffman_constructor, eh_prolog)?;
    helper(image, &HUFFMAN_SHARED, huffman_shared, eh_prolog)?;
    helper(image, &HUFFMAN_COPY, huffman_copy, eh_prolog)?;
    helper(image, &ADD_RECEIVE_TRANSFORM, add_receive_transform, eh_prolog)?;
    require(SEND91.matches(image, send91))?;
    func_info(image, word(image, send91, 9)?)?;
    for operand in SEND91.operands.iter().skip(1) {
        call(image, send91, operand - 1)?;
    }
    require(image.rtti_type(word(image, huffman_constructor, 27)?)? == HUFFMAN_TYPE)?;
    require(call(image, huffman_constructor, 60)? == heap_new)?;
    let control = call(image, huffman_shared, 20)?;
    helper(image, &CONTROL, control, eh_prolog)?;
    require(call(image, control, 29)? == heap_new)?;
    let control_constructor = call(image, control, 50)?;
    helper(image, &CTRLCTOR, control_constructor, eh_prolog)?;
    require(image.rtti_type(word(image, control_constructor, 37)?)? == HUFFMAN_CONTROL_TYPE)?;
    require(image.rtti_type(word(image, control_constructor, 18)?)? == SHARED_CONTROL_TYPE)?;
    let release_inner = release(image, huffman_release, eh_prolog)?;
    require(release(image, tail_release, eh_prolog)? == release_inner)?;
    require(release(image, game_release, eh_prolog)? == release_inner)?;
    // The receiver's argument cleanup uses the same polymorphic shared-control ABI.
    require(release(image, call(image, add_receive_transform, 58)?, eh_prolog)? == release_inner)?;
    helper(image, &HUFFMAN_COPY, call(image, add_receive_transform, 26)?, eh_prolog)?;
    let game_global = game_global(image, getter, eh_prolog)?;
    let disconnect = disconnect(image, game_global, eh_prolog)?;
    Some(Helpers { heap_new, huffman_constructor, huffman_shared, huffman_copy,
        add_receive_transform, send91, huffman_release, disconnect, game_global })
}

/// Recover the retained E3 owner even after its registration operand was overwritten.
/// The tail's stack slots and state numbers must agree with that function's unwind actions.
fn e3_owner(image: &Image<'_>, tail: u32, eh_prolog: u32, candidates: &[u32]) -> Option<u32> {
    let mut found = Vec::new();
    for &entry in candidates {
        let Some(distance) = tail.checked_sub(entry) else { continue };
        if distance >= MAX_E3_ROUTINE_SIZE || call(image, entry, 5) != Some(eh_prolog) { continue; }
        let Some(info) = word(image, entry, 1).and_then(|handler| func_info(image, handler)) else { continue };
        if word(image, info, 4) != Some(E3_EH_STATES) { continue; }
        let unwind = word(image, info, 8)?;
        let mut valid = true;
        for (state, parent) in [(36, 32), (37, 32), (38, 37), (39, 38), (40, 37)] {
            valid &= word(image, unwind, state * UNWIND_ENTRY_SIZE) == Some(parent);
        }
        if !valid { continue; }
        let tail_release = call(image, tail, 135)?;
        let game_release = call(image, tail, 108)?;
        if action(image, unwind, 37, &[0x8d, 0x85, 0x3c, 0xff, 0xff, 0xff, 0x50], &[0xc3]) != Some(tail_release) { continue; }
        if [39, 40].into_iter().any(|state| action(image, unwind, state, &[0x8d, 0x45, 0xe8, 0x50], &[0xc3]) != Some(game_release)) { continue; }
        let Some(argument_release) = action(image, unwind, 38, &[0xff, 0x75, 0xbc], &[0xc3]) else { continue };
        if release(image, argument_release, eh_prolog) != release(image, tail_release, eh_prolog) { continue; }
        let Some(delete) = action(image, unwind, 36, &[0xff, 0x75, 0xbc], &[0x59, 0xc3]) else { continue };
        if !image.is_code(delete) { continue; }
        found.push(entry);
    }
    require(found.len() == 1)?;
    found.first().copied()
}

fn write_word(bytes: &mut [u8], at: usize, value: u32) {
    bytes[at..at + WORD_SIZE].copy_from_slice(&value.to_le_bytes());
}

fn replacement(code: &[u8], va: u32, helpers: &Helpers) -> Option<Vec<u8>> {
    let mut patched = code[PATCH_START..PATCH_END].to_vec();
    patched[..AUTH_SEED.len()].copy_from_slice(&AUTH_SEED);
    patched[CALLBACK_START - PATCH_START..].fill(OPCODE_NOP);
    let mut callback = CALLBACK.bytes.to_vec();
    write_word(&mut callback, GAME_GLOBAL_OPERAND, helpers.game_global);
    let cleanup = va.checked_add(PATCH_END as u32)?;
    let targets = [
        (3, helpers.heap_new), (23, helpers.huffman_constructor), (39, helpers.huffman_shared),
        (58, helpers.huffman_copy), (79, helpers.add_receive_transform), (87, helpers.send91),
        (101, helpers.huffman_release), (106, cleanup), (116, helpers.disconnect), (121, cleanup),
    ];
    for (operand, target) in targets {
        let next = va.checked_add((CALLBACK_START + operand + WORD_SIZE) as u32)?;
        let delta = i32::try_from(i64::from(target) - i64::from(next)).ok()?;
        write_word(&mut callback, operand, delta as u32);
    }
    patched[CALLBACK_START - PATCH_START..CALLBACK_START - PATCH_START + callback.len()].copy_from_slice(&callback);
    Some(patched)
}

fn resolve_at(image: &Image<'_>, va: u32, removed: bool, tails: &[u32], e3_entries: &[u32]) -> Option<ResolvedHandshake> {
    let code = image.read(va, CONNECT_SIZE)?;
    let heap_new = call(image, va, 0x23)?;
    require(HEAP.matches(image, heap_new))?;
    require(image.is_writable_data(word(image, heap_new, 6)?, WORD_SIZE))?;
    call(image, heap_new, 10)?;
    let seed_constructor = call(image, va, 0x37)?;
    let eh_prolog = call(image, seed_constructor, 5)?;
    require(EHPROLOG.matches(image, eh_prolog))?;
    helper(image, &SEED_CONSTRUCTOR, seed_constructor, eh_prolog)?;
    require(image.rtti_type(word(image, seed_constructor, 32)?)? == ".?AVNetMessageSend@@")?;
    require(call(image, seed_constructor, 36)? == heap_new)?;
    helper(image, &SEED_SHARED, call(image, va, 0x4c)?, eh_prolog)?;
    helper(image, &HUFFMAN_COPY, call(image, va, 0x87)?, eh_prolog)?;
    let seed_writer = call(image, va, 0x65)?;
    require(SEED_WRITER.matches(image, seed_writer))?;
    let import = image.import(word(image, seed_writer, 8)?)?;
    require(import.module.eq_ignore_ascii_case("ws2_32.dll") || import.module.eq_ignore_ascii_case("wsock32.dll"))?;
    require(import.name.as_deref() == Some("htonl") || import.ordinal == Some(8))?;
    call(image, seed_writer, 21)?;
    let getter = call(image, va, 0x6f)?;
    require(call(image, va, 0xb0)? == getter)?;
    let game_release = call(image, va, 0xa6)?;
    require(call(image, va, 0xcc)? == game_release)?;
    let seed_release = call(image, va, 0x174)?;
    let huffman_release = unwind_graph(image, va, eh_prolog, seed_release, game_release)?;
    let matches: Vec<_> = tails.iter().filter_map(|tail| {
        validate_helpers(image, *tail, heap_new, getter, huffman_release, eh_prolog).map(|helpers| (*tail, helpers))
    }).collect();
    require(matches.len() == 1)?;
    let (tail, helpers) = &matches[0];
    require(call(image, *tail, 108)? == game_release)?;
    let e3 = e3_owner(image, *tail, eh_prolog, e3_entries)?;
    if !removed {
        require(call(image, va, 0xd3)? == heap_new)?;
        require(call(image, va, 0x12e)? == getter)?;
        require(call(image, va, 0x157)? == game_release)?;
        require(call(image, va, 0x165)? == huffman_release)?;
        for at in [0x108, 0x11f, 0x148] { call(image, va, at)?; }
        require(image.rtti_type(word(image, va, 0xeb)?)? == CALLBACK_TYPE)?;
        require(word(image, va, 0xf5)? == e3)?;
    }
    let patched = replacement(code, va, helpers)?;
    let stock = code[PATCH_START..PATCH_END].to_vec();
    require(!removed || stock == patched)?;
    let offset = image.pe.va_to_offset(va.checked_add(PATCH_START as u32)?)?;
    Some(ResolvedHandshake {
        offset, stock, patched, removed,
        absolute_operands: vec![offset + CALLBACK_START - PATCH_START + GAME_GLOBAL_OPERAND],
    })
}

pub(super) fn resolve(image: &Image<'_>) -> Vec<ResolvedHandshake> {
    let tails = image.scan(&TAIL.pattern());
    let e3_entries = image.scan(&E3_ENTRY.pattern());
    if tails.is_empty() { return Vec::new(); }
    let mut current = CONNECT.pattern();
    current[PATCH_START..PATCH_START + AUTH_SEED.len()].iter_mut().zip(AUTH_SEED).for_each(|(at, byte)| *at = u16::from(byte));
    current[CALLBACK_START..PATCH_END].fill(u16::from(OPCODE_NOP));
    current[CALLBACK_START..CALLBACK_START + CALLBACK.bytes.len()].copy_from_slice(&CALLBACK.pattern());
    image.scan(&CONNECT.pattern()).into_iter().filter_map(|va| resolve_at(image, va, false, &tails, &e3_entries))
        .chain(image.scan(&current).into_iter().filter_map(|va| resolve_at(image, va, true, &tails, &e3_entries))).collect()
}

