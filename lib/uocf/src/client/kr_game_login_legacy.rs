const fn put_word(bytes: &mut [u8], at: usize, value: u32) {
    let encoded = value.to_le_bytes();
    let mut index = 0;
    while index < WORD_SIZE {
        bytes[at + index] = encoded[index];
        index += 1;
    }
}

const fn code_for(build: &ConnectBuild) -> [u8; CONNECT_SIZE] {
    let mut code = STOCK_CODE;
    let mut index = 0;
    while index < OPERANDS.len() {
        put_word(&mut code, OPERANDS[index], build.operands[index]);
        index += 1;
    }
    code
}

const fn pattern_bytes(code: &[u8; CONNECT_SIZE]) -> [u16; CONNECT_SIZE] {
    let mut pattern = [0; CONNECT_SIZE];
    let mut index = 0;
    while index < CONNECT_SIZE {
        pattern[index] = code[index] as u16;
        index += 1;
    }
    pattern
}

const fn stock_patch(code: &[u8; CONNECT_SIZE]) -> [u8; PATCH_SIZE] {
    let mut patch = [0; PATCH_SIZE];
    let mut index = 0;
    while index < PATCH_SIZE {
        patch[index] = code[PATCH_START + index];
        index += 1;
    }
    patch
}

const fn patched_code(code: &[u8; CONNECT_SIZE], build: &ConnectBuild) -> [u8; PATCH_SIZE] {
    let mut patch = stock_patch(code);
    let mut index = 0;
    while index < AUTH_SEED.len() {
        patch[index] = AUTH_SEED[index];
        index += 1;
    }
    let mut callback = HUFFMAN_AND_LOGIN;
    put_word(&mut callback, GAME_GLOBAL_OPERAND, build.game_global);
    let targets = [
        (3, build.heap_new), (23, build.huffman_constructor), (39, build.huffman_shared),
        (58, build.huffman_copy), (79, build.add_receive_transform), (87, build.send91),
        (101, build.huffman_release), (106, build.va + PATCH_END as u32),
        (116, build.disconnect), (121, build.va + PATCH_END as u32),
    ];
    index = 0;
    while index < targets.len() {
        let (at, target) = targets[index];
        assert!(callback[at - 1] == OPCODE_CALL_REL32 || callback[at - 1] == OPCODE_JMP_REL32);
        let next = build.va + CALLBACK_START as u32 + at as u32 + WORD_SIZE as u32;
        put_word(&mut callback, at, target.wrapping_sub(next));
        index += 1;
    }
    index = CALLBACK_START - PATCH_START;
    while index < PATCH_SIZE {
        patch[index] = OPCODE_NOP;
        index += 1;
    }
    index = 0;
    while index < callback.len() {
        patch[CALLBACK_START - PATCH_START + index] = callback[index];
        index += 1;
    }
    patch
}

