const fn stock_patch() -> [u8; PATCH_SIZE] {
    let mut bytes = [0; PATCH_SIZE];
    let mut index = 0;
    while index < PATCH_SIZE {
        bytes[index] = STOCK_CODE[PATCH_START + index];
        index += 1;
    }
    bytes
}

const fn patched_code() -> [u8; PATCH_SIZE] {
    let mut bytes = stock_patch();
    let mut index = 0;
    while index < AUTH_SEED.len() {
        bytes[index] = AUTH_SEED[index];
        index += 1;
    }
    bytes[STATE_IMMEDIATE - PATCH_START] = GAME_READY;
    index = CALLBACK_START - PATCH_START;
    while index < PATCH_SIZE {
        bytes[index] = OPCODE_NOP;
        index += 1;
    }
    index = 0;
    while index < HUFFMAN_AND_LOGIN.len() {
        bytes[CALLBACK_START - PATCH_START + index] = HUFFMAN_AND_LOGIN[index];
        index += 1;
    }
    bytes
}

const fn pattern_bytes() -> [u16; CONNECT_SIZE] {
    let mut bytes = [0; CONNECT_SIZE];
    let mut index = 0;
    while index < CONNECT_SIZE {
        bytes[index] = STOCK_CODE[index] as u16;
        index += 1;
    }
    bytes
}

pub(super) const PATTERN: CipherPattern = CipherPattern {
    bytes: &pattern_bytes(),
    patch_at: PATCH_START,
    stock: &stock_patch(),
    patched: &patched_code(),
    required_va: Some(CONNECT_VA),
};
