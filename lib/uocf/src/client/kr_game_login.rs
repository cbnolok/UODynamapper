const fn put_word(bytes: &mut [u8], at: usize, value: u32) {
    let encoded = value.to_le_bytes();
    let mut index = 0;
    while index < WORD_SIZE {
        bytes[at + index] = encoded[index];
        index += 1;
    }
}

const fn word(bytes: &[u8], at: usize) -> u32 {
    u32::from_le_bytes([bytes[at], bytes[at + 1], bytes[at + 2], bytes[at + 3]])
}

const fn code_for(build: &ConnectBuild) -> [u8; CONNECT_SIZE] {
    let mut bytes = STOCK_CODE;
    let mut index = 0;
    while index < OPERANDS.len() {
        put_word(&mut bytes, OPERANDS[index], build.operands[index]);
        index += 1;
    }
    bytes
}

const fn stock_patch(code: &[u8; CONNECT_SIZE]) -> [u8; PATCH_SIZE] {
    let mut bytes = [0; PATCH_SIZE];
    let mut index = 0;
    while index < PATCH_SIZE {
        bytes[index] = code[PATCH_START + index];
        index += 1;
    }
    bytes
}

const fn patched_code(code: &[u8; CONNECT_SIZE], build: &ConnectBuild) -> [u8; PATCH_SIZE] {
    const SEED_HTONL_OPERAND: usize = 9;
    const CALLBACK_GAME_OPERAND: usize = 46;
    let mut bytes = stock_patch(code);
    let mut index = 0;
    while index < AUTH_SEED.len() {
        bytes[index] = AUTH_SEED[index];
        index += 1;
    }
    put_word(&mut bytes, SEED_HTONL_OPERAND, word(code, HTONL_OPERAND));
    bytes[STATE_IMMEDIATE - PATCH_START] = GAME_READY;
    index = CALLBACK_START - PATCH_START;
    while index < PATCH_SIZE {
        bytes[index] = OPCODE_NOP;
        index += 1;
    }
    let mut callback = HUFFMAN_AND_LOGIN;
    put_word(&mut callback, CALLBACK_GAME_OPERAND, word(code, GAME_GLOBAL_OPERAND));
    // Each offset is the rel32 operand, immediately after its CALL/JMP opcode.
    let targets = [
        (3, build.heap_new), (17, build.huffman_constructor), (30, build.huffman_shared),
        (51, build.add_receive_transform), (60, build.send91),
        (65, build.va + PATCH_END as u32), (76, build.disconnect),
        (81, build.va + SEED_CLEANUP as u32),
    ];
    index = 0;
    while index < targets.len() {
        let (at, target) = targets[index];
        assert!(callback[at - 1] == OPCODE_CALL_REL32 || callback[at - 1] == OPCODE_JMP_REL32);
        let next = build.va + CALLBACK_START as u32 + at as u32 + WORD_SIZE as u32;
        put_word(&mut callback, at, target.wrapping_sub(next));
        index += 1;
    }
    index = 0;
    while index < callback.len() {
        bytes[CALLBACK_START - PATCH_START + index] = callback[index];
        index += 1;
    }
    bytes
}

const fn pattern_bytes(code: &[u8; CONNECT_SIZE]) -> [u16; CONNECT_SIZE] {
    let mut bytes = [0; CONNECT_SIZE];
    let mut index = 0;
    while index < CONNECT_SIZE {
        bytes[index] = code[index] as u16;
        index += 1;
    }
    bytes
}

